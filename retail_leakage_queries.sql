--1.customers
CREATE TABLE rpl_customers (
    customer_id      NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    customer_name    VARCHAR2(100) NOT NULL,
    email            VARCHAR2(100),
    city             VARCHAR2(50),
    state            VARCHAR2(50),
    signup_date      DATE,
    customer_segment VARCHAR2(20)
);

--2.products
CREATE TABLE rpl_products (
    product_id       NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    product_name     VARCHAR2(100) NOT NULL,
    category         VARCHAR2(50),
    sub_category     VARCHAR2(50),
    cost_price       NUMBER(10,2) NOT NULL,
    selling_price    NUMBER(10,2) NOT NULL,
    supplier         VARCHAR2(100)
);

--stores
CREATE TABLE rpl_stores (
    store_id         NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    store_name       VARCHAR2(100) NOT NULL,
    city             VARCHAR2(50),
    state            VARCHAR2(50),
    region           VARCHAR2(50),
    store_type       VARCHAR2(30),
    opening_date     DATE
);

--4.payments
CREATE TABLE rpl_payments (
    payment_id       NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    payment_method   VARCHAR2(30),
    payment_status   VARCHAR2(20)
);

--5.orders
CREATE TABLE rpl_orders (
    order_id         NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    customer_id      NUMBER NOT NULL,
    store_id         NUMBER NOT NULL,
    payment_id       NUMBER,
    order_date       DATE NOT NULL,
    CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id) REFERENCES rpl_customers(customer_id),
    CONSTRAINT fk_orders_store    FOREIGN KEY (store_id)    REFERENCES rpl_stores(store_id),
    CONSTRAINT fk_orders_payment  FOREIGN KEY (payment_id)  REFERENCES rpl_payments(payment_id)
);

--6.order_items
CREATE TABLE rpl_order_items (
    order_item_id       NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    order_id            NUMBER NOT NULL,
    product_id          NUMBER NOT NULL,
    quantity            NUMBER NOT NULL,
    unit_price          NUMBER(10,2) NOT NULL,
    discount_pct        NUMBER(5,2) DEFAULT 0,
    cost_price_at_sale  NUMBER(10,2) NOT NULL,
    CONSTRAINT fk_items_order   FOREIGN KEY (order_id)   REFERENCES rpl_orders(order_id),
    CONSTRAINT fk_items_product FOREIGN KEY (product_id) REFERENCES rpl_products(product_id)
);

--7.inventory
CREATE TABLE rpl_inventory (
    inventory_id      NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    product_id        NUMBER NOT NULL,
    store_id          NUMBER NOT NULL,
    stock_quantity    NUMBER NOT NULL,
    reorder_level     NUMBER DEFAULT 10,
    last_restock_date DATE,
    CONSTRAINT fk_inv_product FOREIGN KEY (product_id) REFERENCES rpl_products(product_id),
    CONSTRAINT fk_inv_store   FOREIGN KEY (store_id)   REFERENCES rpl_stores(store_id)
);

--8.returns
CREATE TABLE rpl_returns (
    return_id        NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    order_item_id    NUMBER NOT NULL,
    return_date      DATE,
    return_reason    VARCHAR2(50),
    refund_amount    NUMBER(10,2),
    CONSTRAINT fk_returns_item FOREIGN KEY (order_item_id) REFERENCES rpl_order_items(order_item_id)
);

